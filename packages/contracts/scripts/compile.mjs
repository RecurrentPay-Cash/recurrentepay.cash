#!/usr/bin/env node
/**
 * Compiles every CashScript contract in `contracts/` to typed artifacts in `artifacts/`.
 *
 * Artifacts are emitted as `*.artifact.ts` (via cashc's `--format ts` equivalent) so the test
 * suite gets full type checking on constructor arguments and `contract.unlock.<fn>(...)` calls.
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { compileFile } from 'cashc';
import { utils } from 'cashc';

const { formatArtifact } = utils;

const here = path.dirname(fileURLToPath(import.meta.url));
const contractsDir = path.resolve(here, '../contracts');
const artifactsDir = path.resolve(here, '../artifacts');

await mkdir(artifactsDir, { recursive: true });

const files = (await readdir(contractsDir)).filter((f) => f.endsWith('.cash')).sort();

if (files.length === 0) {
  console.error('No .cash contracts found in', contractsDir);
  process.exit(1);
}

for (const file of files) {
  const name = file.replace(/\.cash$/, '');
  const artifact = compileFile(path.join(contractsDir, file));
  await writeFile(
    path.join(artifactsDir, `${name}.artifact.ts`),
    `// Generated by scripts/compile.mjs — do not edit.\n${formatArtifact(artifact, 'ts')}`,
  );
  console.log(
    `${name}: ${artifact.bytecode.length / 2} bytes bytecode, ` +
      `${artifact.abi.length} function(s) [${artifact.abi.map((f) => f.name).join(', ')}]`,
  );
}
